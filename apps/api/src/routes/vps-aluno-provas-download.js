'    await pool.query(',
'      "INSERT INTO provas_resultados (prova_id, aluno_id, nota, aprovado, respondido_em) VALUES ($1,$2,$3,$4,NOW()) ON CONFLICT (prova_id, aluno_id) DO UPDATE SET nota = EXCLUDED.nota, aprovado = EXCLUDED.aprovado, respondido_em = NOW()",',
