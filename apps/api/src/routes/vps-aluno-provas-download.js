export default function vpsAlunoProvasDownload(req, res) {
  try {
    const nome = 'alunoProvas.js';
    res.setHeader('Content-Type', 'text/javascript; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${nome}"`);
    res.status(200).send(VPS_ALUNO_PROVAS_CODE);
  } catch (err) {
    logger.error('Falha ao gerar download alunoProvas.js', { err: err?.message });
    res.status(500).json({ error: 'Não foi possível gerar o arquivo.' });
  }
}
