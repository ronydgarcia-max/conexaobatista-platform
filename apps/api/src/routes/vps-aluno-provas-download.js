'      }',
'      // Correção no backend: compara provas_alternativas.correta = true.',
'      if (alt.correta) totalAcertos++;',
'      valuesClauses.push(',
'        "($" + idx + ",$" + (idx + 1) + ",$" + (idx + 2) + ",$" + (idx + 3) + ",NOW())"',
'      );',
'      params.push(provaId, alunoId, r.pergunta_id, r.alternativa_id);',
