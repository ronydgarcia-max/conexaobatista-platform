// download para refletir a configuração efetiva do processo Express.

import logger from '../utils/logger.js';

const FALLBACK_API_URL = 'https://api.conexaobatista.com.br';

function urlSemBarra(url, fallback = '') {
  return String(url || fallback).trim().replace(/\/+$/, '');
}

function detalharUrl(rawUrl, fallback = '') {
  const valor = urlSemBarra(rawUrl, fallback);
  try {
    const parsed = new URL(valor);
    const porta = parsed.port || (parsed.protocol === 'https:' ? '443' : parsed.protocol === 'http:' ? '80' : 'não informada');
    return {
      valor,
      origem: parsed.origin,
      host: parsed.hostname,
      porta,
      path: parsed.pathname || '/',
    };
  } catch (_) {
    return { valor: valor || '(vazio)', origem: 'não analisável', host: 'não analisável', porta: 'não analisável', path: 'não analisável' };
  }
}

function linhaUrl(nome, rawUrl, fallback = '') {
  const item = detalharUrl(rawUrl, fallback);
  return [
    `Variável: ${nome}`,
    `Valor completo (sem segredo): ${item.valor}`,
    `Host: ${item.host}`,
    `Porta efetiva: ${item.porta}`,
    `Path configurado: ${item.path}`,
    `Origem: ${item.origem}`,
  ];
}

