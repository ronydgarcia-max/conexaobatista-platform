'  try {',
'    const { cursoId, provaId } = req.params;',
'    const alunoId = req.usuario.id;',
'',
'    const prova = await buscarProvaValida(provaId, cursoId);',
'    if (!prova) {',
'      return res.status(404).json({ error: "Prova não encontrada para este curso." });',
'    }',
'    if (!(await alunoMatriculado(alunoId, cursoId))) {',
