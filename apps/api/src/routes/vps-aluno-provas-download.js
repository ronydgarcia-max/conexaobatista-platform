'// total_acertos, nota_minima }. Regra de tentativa única: 409 se já respondida.',
'router.post("/provas/:provaId/respostas", async (req, res) => {',
'  try {',
'    const { provaId } = req.params;',
'    const alunoId = req.usuario.id;',
'    const { respostas } = req.body || {};',
'',
'    if (!Array.isArray(respostas) || respostas.length === 0) {',
'      return res.status(400).json({ error: "Respostas inválidas." });',
'    }',
'',
'    const provaRes = await pool.query(',
'      "SELECT id, curso_id, nota_minima FROM provas WHERE id = $1",',
'      [provaId]',
'    );',
'    if (provaRes.rowCount === 0) {',
'      return res.status(404).json({ error: "Prova não encontrada." });',
'    }',
'    const prova = provaRes.rows[0];',
'',
'    if (!(await alunoMatriculado(alunoId, prova.curso_id))) {',
'      return res.status(403).json({ error: "Você não está matriculado neste curso." });',
'    }',
'',
'    // Regra de tentativa única: bloqueia reenvio se já existe resultado.',
'    const jaRespondeu = await pool.query(',
'      "SELECT 1 FROM provas_resultados WHERE prova_id = $1 AND aluno_id = $2 LIMIT 1",',
'      [provaId, alunoId]',
'    );',
'    if (jaRespondeu.rowCount > 0) {',
'      return res.status(409).json({ error: "Esta prova já foi respondida." });',
'    }',
'',
'    // Valida perguntas e alternativas pertencem à prova.',
