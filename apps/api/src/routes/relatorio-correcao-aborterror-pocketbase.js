export default function relatorioCorrecaoAborterrorPocketbase(req, res) {
  try {
    const corpo = montarRelatorio();
    const nome = 'relatorio-correcao-aborterror-pocketbase.txt';
    res.setHeader('Content-Type', 'text/plain; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${nome}"`);
    res.status(200).send(corpo);
  } catch (err) {
    logger.error('Falha ao gerar Relatório de correção AbortError PocketBase', { err: err?.message });
    res.status(500).json({ error: 'Não foi possível gerar o relatório.' });
  }
}
