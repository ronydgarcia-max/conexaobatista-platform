// que carrega apps/api/.env) contra a VPS
// https://api.conexaobatista.com.br/auth/bridge-login.

import logger from '../utils/logger.js';

function mascararSegredo(valor) {
  const v = String(valor || '');
  const len = v.length;
  if (len <= 8) return `(comprimento=${len}; valor omitido por segurança)`;
  return `${v.slice(0, 4)}...${v.slice(-4)} (comprimento=${len})`;
}

