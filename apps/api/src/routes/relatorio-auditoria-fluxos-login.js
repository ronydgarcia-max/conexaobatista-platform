export default async (req, res) => {
  const solicitante = req.admin?.email || req.admin?.id || 'administrador desconhecido';
  logger.info(`[relatorio-auditoria-fluxos-login] Solicitação por: ${solicitante}`);
  const conteudo = montarRelatorio();
  const dataHoraArquivo = new Date().toLocaleString('pt-BR', {
    timeZone: 'America/Sao_Paulo',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).replace(/[/: ]/g, '-');

  res.setHeader('Content-Type', 'text/plain; charset=utf-8');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="relatorio-auditoria-fluxos-login-${dataHoraArquivo}.txt"`,
  );
  res.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate');
  res.setHeader('Pragma', 'no-cache');
  res.setHeader('Expires', '0');
  return res.status(200).send(conteudo);
};
