'    );',
'',
'    const altRes = await pool.query(',
'      "SELECT id, pergunta_id, correta FROM provas_alternativas WHERE pergunta_id = ANY($1::int[])",',
'      [perguntasRes.rows.map(function (p) { return p.id; })]',
'    );',
